"""Rasterise DejaVu Sans Mono Bold into the C glyph tables used by duck_dash.

    python3 tools/make_font.py > main/src/core/font_data.c

Glyphs are ASCII 32..126 as 8-bit coverage (anti-aliased), one table per size.
DejaVu fonts are under the Bitstream Vera / DejaVu license, which allows
embedding; the notice is copied into the generated file.
"""

import sys

from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
SIZES = [("small", 13), ("medium", 17), ("large", 28)]
FIRST, LAST = 32, 126


def raster(px):
    font = ImageFont.truetype(FONT, px)
    ascent, descent = font.getmetrics()
    adv = int(round(font.getlength("M")))
    h = ascent + descent
    rows = []
    for c in range(FIRST, LAST + 1):
        im = Image.new("L", (adv, h), 0)
        ImageDraw.Draw(im).text((0, 0), chr(c), font=font, fill=255)
        rows.append(im.tobytes())
    return adv, h, ascent, rows


def main():
    out = sys.stdout
    out.write("/* Generated by tools/make_font.py from DejaVu Sans Mono Bold. Do not edit.\n")
    out.write(" * DejaVu fonts: Bitstream Vera Fonts Copyright (c) 2003 Bitstream, Inc.,\n")
    out.write(" * DejaVu changes are in the public domain. Redistribution permitted. */\n")
    out.write('#include "gfx.h"\n\n')
    for name, px in SIZES:
        adv, h, ascent, rows = raster(px)
        out.write(f"static const unsigned char {name}_bits[{len(rows)}][{adv * h}] = {{\n")
        for r in rows:
            out.write("  {" + ",".join(str(b) for b in r) + "},\n")
        out.write("};\n")
        out.write(
            f"const gfx_font FONT_{name.upper()} = {{{adv}, {h}, {ascent}, {FIRST}, {LAST}, &{name}_bits[0][0]}};\n\n"
        )


if __name__ == "__main__":
    main()
